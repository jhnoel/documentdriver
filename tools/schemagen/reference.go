package main

import (
	"fmt"
	"reflect"
	"strings"

	"github.com/jhnoel/documentdriver/internal/docx/ops"
)

// reference renders docs/docx-plan.md.
func reference() string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("# docx plan reference\n\n")
	w("<!-- Generated by tools/schemagen from internal/docx/ops. Do not edit. -->\n\n")
	w("A docx plan is a JSON object in the grammar of the agent contract (`docs/contract.md`): `base` (the\n")
	w("`sha256:` hash of the document it was written against), `author`, `change_mode` (`track` or `direct`)\n")
	w("and `ops`, the operations in order. `docs/docx-plan.schema.json` is its JSON Schema. Plans are JSON\n")
	w("only. The operation names and fields are the contract's; each operation names the docxdriver 0.5.2\n")
	w("operation it runs as, which `tools/oracle` translates plans by for parity runs.\n\n")
	w("A rejected plan gets one diagnostic: `invalid_json` (syntax, with the position), `invalid_plan`\n")
	w("(an unknown, missing or mistyped field or a malformed value), `empty_plan`, `invalid_author`, or\n")
	w("`invalid_operation` (the first operation that breaks a rule below; `path` names the field).\n\n")
	w("Lengths are points in multiples of 0.05 (stored as twentieths of a point); indents may be\n")
	w("negative (-100000 to 100000), other lengths may not. Paragraph addresses are eight uppercase\n")
	w("hexadecimal digits or `$alias`; the other addresses are as `docs/contract.md`, section 6, gives them.\n\n")

	w("## Operations\n\n| Operation | Runs as docxdriver's | Change mode | Rules |\n| --- | --- | --- | --- |\n")
	for _, d := range ops.Ops {
		oracle := "– (new)"
		if d.Oracle != "" {
			oracle = "`" + d.OracleName() + "`"
		}
		w("| [`%s`](#%s) | %s | %s | %d |\n", d.Name, strings.ReplaceAll(d.Name, ".", ""), oracle, trackText(d), len(d.Rules))
	}
	w("\nChange-mode classes (docxdriver's tests/change_mode.rs): Exact records revisions only (accept-all\n")
	w("gives the direct result, reject-all the input); KeepsAdditions keeps an empty new header on\n")
	w("reject-all; EmptiesStory leaves an empty story on accept-all; ComplexField writes simple fields as\n")
	w("complex field runs; DirectOnly is refused in track mode; Untracked applies directly in both modes.\n")

	for _, d := range ops.Ops {
		w("\n### %s\n\n%s\n\nChange mode: %s.\n\n", d.Name, d.Description(), trackText(d))
		fieldTable(&b, reflect.TypeOf(d.New()).Elem(), "")
		if len(d.Rules) > 0 {
			w("\n| # | Rule message | Path |\n| --- | --- | --- |\n")
			for i, r := range d.Rules {
				w("| %d | %s | %s |\n", i+1, cell(r.Msg), pathText(r))
			}
		}
	}

	w("\n## Nested types\n")
	for _, t := range []reflect.Type{
		reflect.TypeFor[ops.TableFormat](), reflect.TypeFor[ops.RowFormat](), reflect.TypeFor[ops.CellFormat](),
		reflect.TypeFor[ops.TableBorders](), reflect.TypeFor[ops.TableBorder](), reflect.TypeFor[ops.CellPadding](),
		reflect.TypeFor[ops.ListLevel](), reflect.TypeFor[ops.TextEdit](),
	} {
		w("\n### %s\n\n", t.Name())
		fieldTable(&b, t, "")
	}
	w("\nTableWidth: `{\"unit\": \"auto\"}`, `{\"unit\": \"points\", \"value\": <points>}` or\n")
	w("`{\"unit\": \"percent\", \"value\": <0 < n <= 100>}`. LineSpacing: `{\"mode\": \"multiple\", \"value\": <number>}`,\n")
	w("`{\"mode\": \"exact\" | \"at_least\", \"value\": <points>}`.\n")

	differences(&b)
	return b.String()
}

// trackText returns the change-mode class as text.
func trackText(d ops.OpDef) string {
	return d.Track.String()
}

// cell escapes text for use in a markdown table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	s = strings.ReplaceAll(s, "<", "&lt;")
	return strings.ReplaceAll(s, "\n", " ")
}

// pathText formats a rule's path for the reference table.
func pathText(r ops.Rule) string {
	if r.Explain != nil {
		if p := examplePath(r); p != "" {
			return "by value, e.g. `" + p + "`"
		}
		return "by value"
	}
	if r.Path == "" {
		return "(the operation)"
	}
	return "`" + r.Path + "`"
}

// fieldTable writes a struct's fields.
func fieldTable(b *strings.Builder, t reflect.Type, _ string) {
	fmt.Fprintf(b, "| Field | Type | Required | Values | Stored as |\n| --- | --- | --- | --- | --- |\n")
	for f := range t.Fields() {
		f := f
		tag, ok := f.Tag.Lookup("json")
		if !ok {
			continue
		}
		name, _, _ := strings.Cut(tag, ",")
		req := "yes"
		if def, ok := f.Tag.Lookup("default"); ok && def != "null" {
			req = "no (default `" + def + "`)"
		} else if f.Type.Kind() == reflect.Pointer || ok {
			req = "no"
		}
		values := f.Tag.Get("enum")
		if values != "" {
			values = "`" + strings.ReplaceAll(values, ",", "`, `") + "`"
		}
		desc := f.Tag.Get("doc")
		if desc != "" {
			desc = " " + desc
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s |\n", name, typeText(f.Type)+cell(desc), req, values, f.Tag.Get("schema"))
	}
}

// typeText names a Go type for the reference table.
func typeText(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Pointer:
		return typeText(t.Elem())
	case reflect.Slice:
		return "list of " + typeText(t.Elem())
	case reflect.String:
		if t.PkgPath() != "" {
			return t.Name()
		}
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Uint32, reflect.Uint8:
		return "integer"
	case reflect.Float64:
		return "number"
	}
	return t.Name()
}

// differences writes the intended differences from docxdriver.
func differences(b *strings.Builder) {
	w := func(format string, args ...any) { fmt.Fprintf(b, format, args...) }
	w("\n## Intended differences from docxdriver 0.5.2\n\n")
	w("Parity with docxdriver's plan parsing is on whether a plan is accepted and, when it is refused, the\n")
	w("code (docs/plan.md, decision 2); names, fields, messages and paths are the contract's. The\n")
	w("differential test (internal/docx/ops/oracle_test.go) translates each recorded docxdriver plan into\n")
	w("the contract's grammar (ops.FromOracle), compares the outcome with the recorded oracle result and\n")
	w("fails on any difference not listed here.\n\n")
	w("| Class | Why |\n| --- | --- |\n")
	for _, c := range ops.DifferenceClasses {
		w("| %s | %s |\n", c.Name, cell(c.Why))
	}
	w("\n### Cases\n\n| Class | Case | docxdriver | Go |\n| --- | --- | --- | --- |\n")
	for _, d := range ops.Differences {
		w("| %s | `%s` | %s | %s |\n", d.Class, d.Case, d.Rust, d.Go)
	}
}

// examplePath is the path a by-value rule gives its example, relative to
// the operation.
func examplePath(r ops.Rule) string {
	if r.Example == "" {
		return ""
	}
	plan := `{"base":"sha256:` + strings.Repeat("0", 64) + `","author":"a","change_mode":"track","ops":[` + r.Example + `]}`
	_, d := ops.ParsePlanJSON([]byte(plan))
	if d == nil || d.Code != "invalid_operation" {
		return ""
	}
	return strings.TrimPrefix(strings.TrimPrefix(d.Path, "ops[0]"), ".")
}
