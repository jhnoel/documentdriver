package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"slices"
	"strconv"
	"strings"
)

// generatedHeader is the first line of the generated table file.
const generatedHeader = "// Code generated by tools/vsdorder from the MS-VSDX schema (fetched into a gitignored cache) cross-checked against the Visio-authored corpus; DO NOT EDIT.\n"

// renderTable renders the child-order table of res as Go source.
func renderTable(res *result) ([]byte, error) {
	var b strings.Builder
	b.WriteString(generatedHeader)
	b.WriteString("\npackage schema\n\n")
	b.WriteString("// vTypes holds each tabulated Visio element's children in schema order, as refined by the corpus (the corpus wins every disagreement). It is keyed by element local name as v:<Name>.\n")
	b.WriteString("var vTypes = map[string][]Slot{\n")
	for _, e := range res.entries {
		b.WriteString("\t")
		strconvQuote(&b, "v:"+e.name)
		b.WriteString(": {\n")
		for _, s := range e.slots {
			b.WriteString("\t\t{Names: []Child{")
			for i, n := range s.Names {
				if i > 0 {
					b.WriteString(", ")
				}
				b.WriteString("{\"v\", ")
				strconvQuote(&b, n)
				b.WriteString(", ")
				strconvQuote(&b, "v:"+n)
				b.WriteString("}")
			}
			b.WriteString("}, Multi: ")
			if s.Multi {
				b.WriteString("true")
			} else {
				b.WriteString("false")
			}
			b.WriteString("},\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("// vAttrs holds the Visio elements' attributes' simple types.\n")
	b.WriteString("var vAttrs = map[string]map[string]string{}\n\n")
	b.WriteString("// vSimple holds the Visio simple types the attribute tables use.\n")
	b.WriteString("var vSimple = map[string]Simple{}\n\n")
	b.WriteString("// vRoots holds the complex type of each of the 12 global Visio elements.\n")
	b.WriteString("var vRoots = map[string]string{\n")
	roots := slices.Clone(res.roots)
	slices.SortFunc(roots, func(a, b globalElem) int { return strings.Compare(a.name, b.name) })
	for _, g := range roots {
		b.WriteString("\t")
		strconvQuote(&b, g.name)
		b.WriteString(": ")
		strconvQuote(&b, "v:"+g.name)
		b.WriteString(",\n")
	}
	b.WriteString("}\n")
	src := []byte(b.String())
	out, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("vsdorder: format table: %w", err)
	}
	return out, nil
}

// strconvQuote writes the Go-quoted form of s to b.
func strconvQuote(b *strings.Builder, s string) {
	b.WriteString(strconv.Quote(s))
}

// provenance is the committed record of how the table was made.
type provenance struct {
	Note          string          `json:"note"`
	XSDSHA256     string          `json:"xsd_sha256"`
	XSDFile       string          `json:"xsd_file"`
	ScannedFiles  []string        `json:"scanned_files"`
	AcceptedFiles []string        `json:"accepted_files"`
	Disagreements []disagreementP `json:"disagreements"`
	Refinements   []pairRefP      `json:"refinements"`
	Wildcards     []string        `json:"wildcards"`
}

// disagreementP is the JSON form of one disagreement.
type disagreementP struct {
	Parent   string   `json:"parent,omitempty"`
	Child    string   `json:"child"`
	Kind     string   `json:"kind"`
	Files    int      `json:"files"`
	Parents  int      `json:"parent_occurrences"`
	Occurs   int      `json:"occurrences"`
	Children []string `json:"children,omitempty"`
}

// pairRefP is the JSON form of one refinement record.
type pairRefP struct {
	Parent      string `json:"parent"`
	First       string `json:"first"`
	Second      string `json:"second"`
	Before      int    `json:"before"`
	BeforeFiles int    `json:"before_files"`
	After       int    `json:"after"`
	AfterFiles  int    `json:"after_files"`
}

// renderProvenance renders the provenance record of res as JSON.
func renderProvenance(res *result) ([]byte, error) {
	p := provenance{
		Note:          "Generated by tools/vsdorder from the MS-VSDX schema (never committed) cross-checked against the Visio-authored corpus; do not edit. Regenerate with go run ./tools/vsdorder.",
		XSDSHA256:     res.xsdSHA256,
		XSDFile:       "visio.xsd",
		ScannedFiles:  nonNilStrings(res.scannedFiles),
		AcceptedFiles: nonNilStrings(res.acceptedFiles),
		Wildcards:     nonNilStrings(res.wildcards),
	}
	for _, d := range res.disagreements {
		p.Disagreements = append(p.Disagreements, disagreementP{
			Parent: d.parent, Child: d.child, Kind: d.kind, Files: d.files,
			Parents: d.parents, Occurs: d.occurs, Children: d.children,
		})
	}
	for _, r := range res.refinements {
		p.Refinements = append(p.Refinements, pairRefP{
			Parent: r.parent, First: r.first, Second: r.second, Before: r.before,
			BeforeFiles: r.beforeFiles, After: r.after, AfterFiles: r.afterFiles,
		})
	}
	return marshalIndent(p)
}

// marshalIndent renders v as indented JSON with a trailing newline.
func marshalIndent(v any) ([]byte, error) {
	b, err := json.MarshalIndent(v, "", "\t")
	if err != nil {
		return nil, fmt.Errorf("vsdorder: marshal provenance: %w", err)
	}
	b = bytes.TrimSpace(b)
	b = append(b, '\n')
	return b, nil
}

// nonNilStrings returns ss, or an empty slice when ss is nil, so the
// JSON renders [] rather than null.
func nonNilStrings(ss []string) []string {
	if ss == nil {
		return []string{}
	}
	return ss
}
