// maxPart bounds every member read from a corpus file.
const maxPart = 16 << 20

// officeApps maps the <Application> value of docProps/app.xml to the
// product family. Only files an Office product wrote count: LibreOffice,
// WPS, Outlook and unlabelled files are not authorities for what Office
// writes.
var officeApps = map[string]string{
	"Microsoft Office Word":          "word",
	"Microsoft Macintosh Word":       "word",
	"Microsoft Word":                 "word",
	"Microsoft Office PowerPoint":    "powerpoint",
	"Microsoft Macintosh PowerPoint": "powerpoint",
	"Microsoft PowerPoint":           "powerpoint",
	"Microsoft Excel":                "excel",
	"Microsoft Macintosh Excel":      "excel",
	"Microsoft Visio":                "visio",
}

const (
	nsTypes = "http://schemas.openxmlformats.org/package/2006/content-types"
	nsRels  = "http://schemas.openxmlformats.org/package/2006/relationships"
	nsApp   = "http://schemas.openxmlformats.org/officeDocument/2006/extended-properties"
)

// Source names the file an entry was first seen in. Path is relative to
// a named corpus root, never absolute.
type Source struct {
	Label  string `json:"label"`
	Path   string `json:"path"`
	SHA256 string `json:"sha256"`
}

// Entry is one content type or relationship type with its evidence.
type Entry struct {
	Value string `json:"value"`
	// Files counts distinct Office-authored files that use it, Word,
	// PowerPoint, Excel and Visio separately.
	Files      int    `json:"files"`
	Word       int    `json:"word"`
	PowerPoint int    `json:"powerpoint"`
	Excel      int    `json:"excel"`
	Visio      int    `json:"visio"`
	Source     Source `json:"source"`
	// External counts files where a relationship of this type has
	// TargetMode="External" (relationship types only).
	External int `json:"external,omitempty"`
	// ExternalExcel is the part of External seen in Excel files, so that
	// the Word and PowerPoint view (RenderJSON) can leave it out.
	ExternalExcel int `json:"external_excel,omitempty"`
	// ExternalVisio is the part of External seen in Visio files, left
	// out of that view for the same reason.
	ExternalVisio int `json:"external_visio,omitempty"`
}

// Pair says a relationship type targeted a part of a content type.
type Pair struct {
	Rel         string `json:"rel"`
	ContentType string `json:"content_type"`
	Files       int    `json:"files"`
	Word        int    `json:"word"`
	PowerPoint  int    `json:"powerpoint"`
	Excel       int    `json:"excel"`
	Visio       int    `json:"visio"`
	Source      Source `json:"source"`
}

// ScanInfo describes one corpus root that was scanned.
type ScanInfo struct {
	Label    string         `json:"label"`
	Scanned  int            `json:"scanned"`
	Accepted int            `json:"accepted"`
	ByApp    map[string]int `json:"accepted_by_application"`
}

// Provenance is the committed record the table is rendered from.
type Provenance struct {
	Note         string     `json:"note"`
	MinFiles     int        `json:"min_files"`
	Scans        []ScanInfo `json:"scans"`
	ContentTypes []Entry    `json:"content_types"`
	RelTypes     []Entry    `json:"rel_types"`
	RelTargets   []Pair     `json:"rel_targets"`
}

// Root is a labelled corpus directory.
type Root struct{ Label, Dir string }

type acc struct {
	files, word, ppt, excel, visio, external, externalExcel, externalVisio int
	src                                                                    Source
}

// add records one file of family family using entry, noting an external relationship.
func (a *acc) add(family string, src Source, ext bool) {
	if a.files == 0 {
		a.src = src
	}
	a.files++
	switch family {
	case "word":
		a.word++
	case "excel":
		a.excel++
	case "visio":
		a.visio++
	default:
		a.ppt++
	}
	if ext {
		a.external++
		switch family {
		case "excel":
			a.externalExcel++
		case "visio":
			a.externalVisio++
		}
	}
}

// Extract scans the roots and returns the provenance record. Files are
// visited in sorted order within each root, in root order, so the first
// source of an entry is deterministic.
func Extract(roots []Root, minFiles int) (*Provenance, error) {
	p := &Provenance{
		Note:     "Generated by tools/ctypesgen -extract from Office-authored files; do not edit. Render with go generate ./internal/ooxml/ctypes.",
		MinFiles: minFiles,
	}
	cts := map[string]*acc{}
	rels := map[string]*acc{}
	pairs := map[[2]string]*acc{}
	for _, r := range roots {
		files, err := listPackages(r.Dir)
		if err != nil {
			return nil, err
		}
		info := ScanInfo{Label: r.Label, ByApp: map[string]int{}}
		for _, rel := range files {
			info.Scanned++
			full := filepath.Join(r.Dir, filepath.FromSlash(rel))
			pk, err := readPackage(full)
			if err != nil {
				continue // not a readable package; not an authority
			}
			if pk.family == "" {
				continue
			}
			info.Accepted++
			info.ByApp[pk.app]++
			src := Source{Label: r.Label, Path: rel, SHA256: pk.sum}
			for ct := range pk.contentTypes {
				bump(cts, ct, pk.family, src, false)
			}
			for rt, ext := range pk.relTypes {
				bump(rels, rt, pk.family, src, ext)
			}
			for pr := range pk.pairs {
				bump(pairs, pr, pk.family, src, false)
			}
		}
		p.Scans = append(p.Scans, info)
	}
	for v, a := range cts {
		if a.files >= minFiles {
			p.ContentTypes = append(p.ContentTypes, entry(v, a))
		}
	}
	for v, a := range rels {
		if a.files >= minFiles {
			p.RelTypes = append(p.RelTypes, entry(v, a))
		}
	}
	for k, a := range pairs {
		if a.files >= minFiles {
			p.RelTargets = append(p.RelTargets, Pair{Rel: k[0], ContentType: k[1], Files: a.files, Word: a.word, PowerPoint: a.ppt, Excel: a.excel, Visio: a.visio, Source: a.src})
		}
	}
	sort.Slice(p.ContentTypes, func(i, j int) bool { return p.ContentTypes[i].Value < p.ContentTypes[j].Value })
	sort.Slice(p.RelTypes, func(i, j int) bool { return p.RelTypes[i].Value < p.RelTypes[j].Value })
	sort.Slice(p.RelTargets, func(i, j int) bool {
		if p.RelTargets[i].Rel != p.RelTargets[j].Rel {
			return p.RelTargets[i].Rel < p.RelTargets[j].Rel
		}
		return p.RelTargets[i].ContentType < p.RelTargets[j].ContentType
	})
	return p, nil
}

// bump adds one occurrence of key to accumulator map m.
func bump[K comparable](m map[K]*acc, k K, family string, src Source, ext bool) {
	a := m[k]
	if a == nil {
		a = &acc{}
		m[k] = a
	}
	a.add(family, src, ext)
}

// entry converts accumulator a for value v into an Entry.
func entry(v string, a *acc) Entry {
	return Entry{Value: v, Files: a.files, Word: a.word, PowerPoint: a.ppt, Excel: a.excel, Visio: a.visio, Source: a.src, External: a.external, ExternalExcel: a.externalExcel, ExternalVisio: a.externalVisio}

}

// listPackages returns the .docx, .pptx, .potx, .xlsx, .xlsm, .xltx and
// .xltm files under dir as
// sorted slash-separated relative paths.
func listPackages(dir string) ([]string, error) {
	var out []string
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		switch strings.ToLower(filepath.Ext(p)) {
		case ".docx", ".pptx", ".potx", ".xlsx", ".xlsm", ".xltx", ".xltm", ".vsdx", ".vsdm", ".vstx", ".vstm", ".vssx", ".vssm":
			rel, err := filepath.Rel(dir, p)
			if err != nil {
				return err
			}
			out = append(out, filepath.ToSlash(rel))
		}
		return nil
	})
	sort.Strings(out)
	return out, err
}

type pkgFacts struct {
	app, family  string
	sum          string
	contentTypes map[string]bool
	relTypes     map[string]bool // relationship type -> any external
	pairs        map[[2]string]bool
}

// readPackage reads an Office package's content and relationship types and returns its facts.
func readPackage(file string) (*pkgFacts, error) {
	raw, err := os.ReadFile(file) //nolint:gosec // G304: the corpus path is the developer's argument
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(raw)
	zr, err := zip.OpenReader(file)
	if err != nil {
		return nil, err
	}
	defer zr.Close()
	byName := map[string]*zip.File{}
	var names []string
	for _, f := range zr.File {
		if strings.HasSuffix(f.Name, "/") {
			continue
		}
		byName["/"+strings.ToLower(f.Name)] = f
		names = append(names, "/"+f.Name)
	}
	pf := &pkgFacts{sum: hex.EncodeToString(sum[:]), contentTypes: map[string]bool{}, relTypes: map[string]bool{}, pairs: map[[2]string]bool{}}
	app, err := application(byName)
	if err != nil {
		return pf, nil
	}
	pf.app, pf.family = app, officeApps[app]
	if pf.family == "" {
		return pf, nil
	}
	ctDoc, err := parseMember(byName["/[content_types].xml"])
	if err != nil {
		return nil, err
	}
	defaults := map[string]string{}
	overrides := map[string]string{}
	for _, e := range ctDoc.Root().Elements() {
		ct, _ := e.Attr("ContentType")
		switch {
		case e.Is(nsTypes, "Default"):
			ext, _ := e.Attr("Extension")
			defaults[strings.ToLower(ext)] = ct
		case e.Is(nsTypes, "Override"):
			pn, _ := e.Attr("PartName")
			overrides[strings.ToLower(pn)] = ct
		}
	}
	typeOf := func(name string) string {
		if ct, ok := overrides[strings.ToLower(name)]; ok {
			return ct
		}
		ext := strings.TrimPrefix(strings.ToLower(path.Ext(name)), ".")
		return defaults[ext]
	}
	for _, n := range names {
		if strings.EqualFold(n, "/[Content_Types].xml") {
			continue
		}
		if ct := typeOf(n); ct != "" {
			pf.contentTypes[ct] = true
		}
	}
	for _, n := range names {
		if !strings.HasSuffix(strings.ToLower(n), ".rels") {
			continue
		}
		doc, err := parseMember(byName[strings.ToLower(n)])
		if err != nil {
			continue
		}
		source := sourceOfRels(n)
		for _, e := range doc.Root().Elements() {
			if !e.Is(nsRels, "Relationship") {
				continue
			}
			typ, _ := e.Attr("Type")
			mode, _ := e.Attr("TargetMode")
			target, _ := e.Attr("Target")
			if typ == "" {
				continue
			}
			if strings.EqualFold(mode, "External") {
				pf.relTypes[typ] = true
				continue
			}
			if _, ok := pf.relTypes[typ]; !ok {
				pf.relTypes[typ] = false
			}
			part := resolveTarget(source, target)
			if _, ok := byName[strings.ToLower(part)]; !ok {
				continue
			}
			if ct := typeOf(part); ct != "" {
				pf.pairs[[2]string{typ, ct}] = true
			}
		}
	}
	return pf, nil
}

// sourceOfRels returns the part a relationships part belongs to ("/" for
// the package).
func sourceOfRels(rels string) string {
	dir, file := path.Split(rels)
	dir = strings.TrimSuffix(dir, "_rels/")
	file = strings.TrimSuffix(file, ".rels")
	if file == "" {
		return "/"
	}
	return dir + file
}

// resolveTarget resolves target against source part into a package path.
func resolveTarget(source, target string) string {
	if strings.HasPrefix(target, "/") {
		return path.Clean(target)
	}
	dir := "/"
	if source != "/" {
		dir = path.Dir(source)
	}
	return path.Join(dir, target)
}

// application returns the Application value from docProps/app.xml in byName.
func application(byName map[string]*zip.File) (string, error) {
	f := byName["/docprops/app.xml"]
	if f == nil {
		return "", errors.New("no app.xml")
	}
	doc, err := parseMember(f)
	if err != nil {
		return "", err
	}
	for _, e := range doc.Root().Elements() {
		if e.Is(nsApp, "Application") {
			return strings.TrimSpace(e.Text()), nil
		}
	}
	return "", errors.New("no Application")
}

// parseMember parses zip member f as a tree document, erroring if missing or oversized.
func parseMember(f *zip.File) (*tree.Document, error) {
	if f == nil {
		return nil, errors.New("member missing")
	}
	rc, err := f.Open()
	if err != nil {
		return nil, err
	}
	defer rc.Close()
	b, err := io.ReadAll(io.LimitReader(rc, maxPart+1))
	if err != nil {
		return nil, err
	}
	if len(b) > maxPart {
		return nil, fmt.Errorf("%s: member over %d bytes", f.Name, maxPart)
	}
	return tree.Parse(b)
}
