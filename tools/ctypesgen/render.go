// Names assigns each value a Go identifier: prefix plus a short CamelCase
// form of the value, lengthening to the whole value on a collision. Values
// are visited in priority order, so the ECMA-376 names keep the short form.
func names(prefix string, values []string, short func(string) []string) (map[string]string, error) {
	order := append([]string(nil), values...)
	sort.SliceStable(order, func(i, j int) bool {
		pi, pj := priority(order[i]), priority(order[j])
		if pi != pj {
			return pi < pj
		}
		return order[i] < order[j]
	})
	used := map[string]string{}
	out := map[string]string{}
	for _, v := range order {
		var name string
		for _, toks := range [][]string{short(v), lastTwo(v), tokens(v)} {
			c := prefix + camel(toks)
			if _, taken := used[c]; !taken {
				name = c
				break
			}
		}
		if name == "" {
			return nil, fmt.Errorf("cannot name %q: %q and it collide even with the whole value", v, used[prefix+camel(tokens(v))])
		}
		used[name] = v
		out[v] = name
	}
	return out, nil
}

// priority ranks a value's naming order, lower first for ECMA-376 names.
func priority(v string) int {
	switch {
	case strings.Contains(v, "/officedocument/"):
		return 1 // a lower-case spelling Office writes for core properties: not the canonical name
	case strings.Contains(v, "schemas.openxmlformats.org"), strings.HasPrefix(v, "application/vnd.openxmlformats"):
		return 0
	case strings.HasPrefix(v, "image/"), strings.HasPrefix(v, "application/xml"), strings.HasPrefix(v, "text/"):
		return 1
	case strings.Contains(v, "microsoft.com"), strings.Contains(v, "vnd.ms-"):
		return 2
	default:
		return 3
	}
}

// lastTwo is the last two path segments of a URI, the second candidate
// when the last alone collides (metadata/core-properties).
func lastTwo(v string) []string {
	parts := strings.Split(v, "/")
	if len(parts) > 2 {
		parts = parts[len(parts)-2:]
	}
	return tokens(strings.Join(parts, "/"))
}

// tokens splits v into letter-and-digit tokens.
func tokens(v string) []string {
	return strings.FieldsFunc(v, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) })
}

// camel joins toks as CamelCase, prefixing N if it starts with a digit.
func camel(toks []string) string {
	var sb strings.Builder
	for _, t := range toks {
		r := []rune(t)
		r[0] = unicode.ToUpper(r[0])
		sb.WriteString(string(r))
	}
	s := sb.String()
	if s != "" && unicode.IsDigit([]rune(s)[0]) {
		s = "N" + s
	}
	return s
}

// shortContentType returns the short token form of a content type value.
func shortContentType(v string) []string {
	for _, p := range []string{"application/vnd.openxmlformats-officedocument.", "application/vnd.openxmlformats-package.", "application/vnd.ms-", "application/vnd."} {
		if rest, ok := strings.CutPrefix(v, p); ok {
			toks := tokens(rest)
			if strings.HasSuffix(v, "+xml") && len(toks) > 1 {
				toks = toks[:len(toks)-1]
			}
			if p == "application/vnd.openxmlformats-package." {
				toks = append([]string{"package"}, toks...)
			}
			if p == "application/vnd.ms-" {
				toks = append([]string{"ms"}, toks...)
			}
			return toks
		}
	}
	return tokens(v)
}

// shortRel returns the token form of a relationship type's last segment.
func shortRel(v string) []string {
	i := strings.LastIndex(v, "/")
	return tokens(v[i+1:])
}

// entryLit renders one table entry as a Go struct literal.
func entryLit(name string, e Entry) string {
	return fmt.Sprintf("{Name: %q, Value: %q, Files: %d, Word: %d, PowerPoint: %d, Excel: %d, Visio: %d, External: %d, Source: %q, SHA256: %q},\n",
		name, e.Value, e.Files, e.Word, e.PowerPoint, e.Excel, e.Visio, e.External, e.Source.Label+"/"+e.Source.Path, e.Source.SHA256)
}

// RenderGo returns the source of internal/ooxml/ctypes/table_gen.go.
func RenderGo(p *Provenance) ([]byte, error) {
	var cv, rv []string
	for _, e := range p.ContentTypes {
		cv = append(cv, e.Value)
	}
	for _, e := range p.RelTypes {
		rv = append(rv, e.Value)
	}
	cn, err := names("CT", cv, shortContentType)
	if err != nil {
		return nil, err
	}
	rn, err := names("Rel", rv, shortRel)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/ctypesgen from provenance.json; DO NOT EDIT.\n\n")
	b.WriteString("package ctypes\n\n")
	fmt.Fprintf(&b, "// Content types used by at least %d Office-authored files (see provenance.json).\n", p.MinFiles)
	b.WriteString("const (\n")
	for _, e := range p.ContentTypes {
		fmt.Fprintf(&b, "\t%s = %q\n", cn[e.Value], e.Value)
	}
	b.WriteString(")\n\n")
	fmt.Fprintf(&b, "// Relationship types used by at least %d Office-authored files.\n", p.MinFiles)
	b.WriteString("const (\n")
	for _, e := range p.RelTypes {
		fmt.Fprintf(&b, "\t%s = %q\n", rn[e.Value], e.Value)
	}
	b.WriteString(")\n\n")
	b.WriteString("var contentTypes = []Entry{\n")
	for _, e := range p.ContentTypes {
		b.WriteString("\t" + entryLit(cn[e.Value], e))
	}
	b.WriteString("}\n\nvar relTypes = []Entry{\n")
	for _, e := range p.RelTypes {
		b.WriteString("\t" + entryLit(rn[e.Value], e))
	}
	b.WriteString("}\n\n// relTargets lists, per relationship type, the content types of the parts\n// it targeted in Office-authored files.\nvar relTargets = []Target{\n")
	for _, t := range p.RelTargets {
		fmt.Fprintf(&b, "\t{Rel: %s, ContentType: %s, Files: %d, Word: %d, PowerPoint: %d, Excel: %d, Visio: %d, Source: %q},\n",
			relName(rn, t.Rel), ctName(cn, t.ContentType), t.Files, t.Word, t.PowerPoint, t.Excel, t.Visio, t.Source.Label+"/"+t.Source.Path)
	}
	b.WriteString("}\n")
	fmt.Fprintf(&b, "\n// minFiles is the evidence threshold the table was extracted with.\nconst minFiles = %d\n", p.MinFiles)

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt generated table: %w", err)
	}
	return out, nil
}

// relName returns the constant for a relationship type in a target
// pair, or the quoted literal when the type itself fell under the
// threshold (a pair is only kept when both are, so this is a fallback).
func relName(rn map[string]string, v string) string {
	if n, ok := rn[v]; ok {
		return n
	}
	return strconv.Quote(v)
}

// ctName returns the Go constant name for content type v, or its quoted literal.
func ctName(cn map[string]string, v string) string {
	if n, ok := cn[v]; ok {
		return n
	}
	return strconv.Quote(v)
}

// RenderJSON returns tools/conformance/ctypes.json, the table as the
// Python integrity checker reads it. The checker guards docx and pptx
// outputs, so it gets the Word and PowerPoint view: entries and pairs
// seen in at least MinFiles Word or PowerPoint files, and the external
// relationship types those files show. Evidence from Excel or Visio
// files alone does not widen it.
func RenderJSON(p *Provenance) ([]byte, error) {
	type out struct {
		Note            string              `json:"note"`
		MinFiles        int                 `json:"min_files"`
		RelContentTypes map[string][]string `json:"rel_content_types"`
		RelExternal     []string            `json:"rel_external"`
		ContentTypes    []string            `json:"content_types"`
		RelTypes        []string            `json:"rel_types"`
	}
	o := out{
		Note:            "Generated by tools/ctypesgen from internal/ooxml/ctypes/provenance.json; do not edit.",
		MinFiles:        p.MinFiles,
		RelContentTypes: map[string][]string{},
		RelExternal:     []string{},
		ContentTypes:    []string{},
		RelTypes:        []string{},
	}
	for _, t := range p.RelTargets {
		if t.Word+t.PowerPoint >= p.MinFiles {
			o.RelContentTypes[t.Rel] = append(o.RelContentTypes[t.Rel], t.ContentType)
		}
	}
	for _, e := range p.RelTypes {
		if e.Word+e.PowerPoint < p.MinFiles {
			continue
		}
		o.RelTypes = append(o.RelTypes, e.Value)
		if e.External-e.ExternalExcel-e.ExternalVisio > 0 {
			o.RelExternal = append(o.RelExternal, e.Value)
		}
	}
	for _, e := range p.ContentTypes {
		if e.Word+e.PowerPoint >= p.MinFiles {
			o.ContentTypes = append(o.ContentTypes, e.Value)
		}
	}
	return marshal(o)
}

// marshal encodes v as indented JSON without HTML escaping.
func marshal(v any) ([]byte, error) {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}
