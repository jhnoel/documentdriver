package main

import (
	"archive/zip"
	"bytes"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"fmt"
	"io/fs"
	"maps"
	"os"
	"path"
	"path/filepath"
	"slices"
	"sort"
	"strings"
	"time"
)

// distName is the distribution (and import package) name of the wheel.
const distName = "documentdriver"

// pythonSource is the directory, relative to the repository root, holding
// the import package that goes into every wheel.
const pythonSource = "packaging/python/" + distName

// zipTime is the modification time of every wheel entry: the earliest a
// zip can record, so the archive depends on its contents alone.
var zipTime = time.Date(1980, 1, 1, 0, 0, 0, 0, time.UTC)

// wheelFile is one file of a wheel.
type wheelFile struct {
	Name string // slash-separated path inside the wheel
	Data []byte
	Exec bool
}

// wheelName is the PEP 427 file name of the wheel for a platform tag
// set: the platform part joins the tags with '.', the PEP 425
// compressed tag set, so one file covers every tag.
func wheelName(pyVersion string, tags []string) string {
	return distName + "-" + pyVersion + "-py3-none-" + strings.Join(tags, ".") + ".whl"
}

// distInfo is the wheel's .dist-info directory.
func distInfo(pyVersion string) string {
	return distName + "-" + pyVersion + ".dist-info"
}

// recordHash is a RECORD hash: sha256= and the URL-safe base64 digest
// without padding (PEP 376, PEP 427).
func recordHash(b []byte) string {
	sum := sha256.Sum256(b)
	return "sha256=" + base64.RawURLEncoding.EncodeToString(sum[:])
}

// readPackage reads the import package sources under root/pythonSource,
// skipping caches and compiled files.
func readPackage(root string) ([]wheelFile, error) {
	dir := filepath.Join(root, filepath.FromSlash(pythonSource))
	var files []wheelFile
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if d.Name() == "__pycache__" {
				return filepath.SkipDir
			}
			return nil
		}
		if strings.HasSuffix(p, ".pyc") || d.Name() == "_digests.py" || d.Name() == ".DS_Store" {
			return nil
		}
		rel, err := filepath.Rel(dir, p)
		if err != nil {
			return err
		}
		b, err := os.ReadFile(p) //nolint:gosec // G304: a file of the repository's own package source
		if err != nil {
			return err
		}
		files = append(files, wheelFile{Name: distName + "/" + filepath.ToSlash(rel), Data: b})
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("read the Python package %s: %w", pythonSource, err)
	}
	return files, nil
}

// digestsModule is the generated documentdriver/_digests.py: the version
// and the SHA-256 of every bundled binary, which binary() checks.
func digestsModule(pyVersion string, bins map[string][]byte) []byte {
	var b strings.Builder
	b.WriteString("# Generated by tools/release when the wheel was built; do not edit.\n")
	fmt.Fprintf(&b, "VERSION = %q\n", pyVersion)
	b.WriteString("DIGESTS = {\n")
	for _, name := range sortedKeys(bins) {
		sum := sha256.Sum256(bins[name])
		fmt.Fprintf(&b, "    %q: %q,\n", name, hex.EncodeToString(sum[:]))
	}
	b.WriteString("}\n")
	return []byte(b.String())
}

// metadata is the core metadata file (METADATA) of the wheel.
func metadata(pyVersion string, bins map[string][]byte) []byte {
	names := joinNames(sortedKeys(bins))
	return []byte("Metadata-Version: 2.1\n" +
		"Name: " + distName + "\n" +
		"Version: " + pyVersion + "\n" +
		"Summary: The documentdriver " + names + " command-line tools, as static binaries\n" +
		"Requires-Python: >=3.8\n" +
		"Description-Content-Type: text/markdown\n" +
		"\n" +
		"# documentdriver\n\n" +
		"The " + names + " command-line tools of documentdriver for one platform,\n" +
		"static binaries that read and edit Office documents for agents.\n\n" +
		"```python\nimport documentdriver\n" +
		"with open(\"report.docx\", \"rb\") as f:\n" +
		"    facts, _ = documentdriver.run(\"docx\", [\"read\", \"in.docx\"], {\"in.docx\": f.read()})\n```\n\n" +
		"`run()` makes one call in a private directory and returns the parsed\n" +
		"result, or raises `EngineError` with the contract's errors.\n" +
		"`binary(name)` returns the bundled binary's path after checking it against\n" +
		"the SHA-256 recorded when the wheel was built.\n")
}

// joinNames joins names as English prose: "a", "a and b", "a, b and c".
func joinNames(names []string) string {
	if len(names) <= 1 {
		return strings.Join(names, "")
	}
	return strings.Join(names[:len(names)-1], ", ") + " and " + names[len(names)-1]
}

// wheelMeta is the WHEEL file of a wheel for a platform tag set: one
// Tag line per expanded tag, in the order tags gives.
func wheelMeta(tags []string) []byte {
	var b strings.Builder
	b.WriteString("Wheel-Version: 1.0\n")
	b.WriteString("Generator: documentdriver tools/release\n")
	b.WriteString("Root-Is-Purelib: false\n")
	for _, tag := range tags {
		fmt.Fprintf(&b, "Tag: py3-none-%s\n", tag)
	}
	return []byte(b.String())
}

// makeWheel builds the wheel for one platform: the import package, the
// generated digests, the binaries under documentdriver/bin, and the
// .dist-info files with RECORD last. The bytes are a function of the
// inputs: sorted entries, one fixed time, fixed modes.
func makeWheel(pyVersion string, tags []string, pkg []wheelFile, bins map[string][]byte) ([]byte, error) {
	files := append([]wheelFile(nil), pkg...)
	files = append(files, wheelFile{Name: distName + "/_digests.py", Data: digestsModule(pyVersion, bins)})
	for _, name := range sortedKeys(bins) {
		files = append(files, wheelFile{Name: distName + "/bin/" + name, Data: bins[name], Exec: true})
	}
	sort.Slice(files, func(i, j int) bool { return files[i].Name < files[j].Name })
	info := distInfo(pyVersion)
	files = append(files,
		wheelFile{Name: info + "/METADATA", Data: metadata(pyVersion, bins)},
		wheelFile{Name: info + "/WHEEL", Data: wheelMeta(tags)},
	)
	var record strings.Builder
	for _, f := range files {
		fmt.Fprintf(&record, "%s,%s,%d\n", f.Name, recordHash(f.Data), len(f.Data))
	}
	record.WriteString(info + "/RECORD,,\n")
	files = append(files, wheelFile{Name: info + "/RECORD", Data: []byte(record.String())})

	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	for _, f := range files {
		if path.Clean(f.Name) != f.Name || strings.HasPrefix(f.Name, "/") {
			return nil, fmt.Errorf("wheel entry %q is not a clean relative path", f.Name)
		}
		h := &zip.FileHeader{Name: f.Name, Method: zip.Deflate, Modified: zipTime}
		mode := fs.FileMode(0o644)
		if f.Exec {
			mode = 0o755
		}
		h.SetMode(mode)
		w, err := zw.CreateHeader(h)
		if err != nil {
			return nil, fmt.Errorf("wheel entry %s: %w", f.Name, err)
		}
		if _, err := w.Write(f.Data); err != nil {
			return nil, fmt.Errorf("wheel entry %s: %w", f.Name, err)
		}
	}
	if err := zw.Close(); err != nil {
		return nil, fmt.Errorf("close the wheel: %w", err)
	}
	return buf.Bytes(), nil
}

// sortedKeys returns the map keys in sorted order.
func sortedKeys[V any](m map[string]V) []string { return slices.Sorted(maps.Keys(m)) }
