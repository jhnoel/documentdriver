// The write comparison outcomes of one plan in one mode.
const (
	wIdentical      = "identical"       // every compared field equal
	wDiffer         = "differ"          // some field differs (listed)
	wNotImplemented = "not-implemented" // the Go CLI cannot apply the plan yet
	wNoBaseline     = "no-baseline"     // nothing recorded for the plan
	wIntended       = "intended"        // differs only as the known files list
)

var wOutcomes = []string{wIdentical, wDiffer, wNotImplemented, wNoBaseline, wIntended}

// rootDir returns the repository root.
func rootDir() (string, error) { return repo.Root() }

// compareWrite lists the semantic fields where the Go run differs from
// the record: outcome, refusal code and path, each projection, the
// integrity findings it introduced, and parts the oracle left alone that
// the Go output changed. Field names: outcome, code, path, proj:<name>,
// integrity, part:<+|-|~name>.
func compareWrite(want, got *writeResult) []string {
	var diffs []string
	if want.Outcome != got.Outcome {
		diffs = append(diffs, "outcome")
	}
	if want.Code != got.Code {
		diffs = append(diffs, "code")
	}
	if want.Path != got.Path {
		diffs = append(diffs, "path")
	}
	for _, k := range slices.Sorted(maps.Keys(want.Proj)) {
		if got.Proj[k] != want.Proj[k] {
			diffs = append(diffs, "proj:"+k)
		}
	}
	if !slices.Equal(want.Integrity, got.Integrity) {
		diffs = append(diffs, "integrity")
	}
	for _, part := range got.Parts {
		if !slices.Contains(want.Parts, part) && !slices.Contains(want.Parts, "~"+part[1:]) {
			diffs = append(diffs, "part:"+part)
		}
	}
	return diffs
}

// preexistingRefusals are the codes with which docxdriver refuses a
// document over defects it already had (its integrity gate, or a source
// it cannot parse), not over the edit.
var preexistingRefusals = []string{"invalid_output", "invalid_document"}

// compareDirty checks the dirty family's own rule (owner decision
// 2026-11-13): schema and integrity checks may only stop the tool from
// introducing nonconformities, never over pre-existing ones. The Go run
// must save, introduce no finding and drop none of the input's (each
// pre-existing defect is left alone). Where docxdriver refused because
// of a pre-existing defect, that is a docxdriver bug: the oracle's
// outcome and projections are not expected (reported as intended); else
// the run is compared as usual too.
func compareDirty(want, got *writeResult) (diffs []string, oracleBug bool) {
	if got.Outcome != "accepted" && want.Outcome == "accepted" {
		diffs = append(diffs, "outcome")
	}
	if len(got.Integrity) > 0 {
		diffs = append(diffs, "integrity")
	}
	if len(got.Dropped) > 0 {
		diffs = append(diffs, "dropped")
	}
	if want.Outcome == "refused" && slices.Contains(preexistingRefusals, want.Code) {
		if got.Outcome != "accepted" {
			diffs = append(diffs, "outcome")
		}
		return diffs, true
	}
	for _, d := range compareWrite(want, got) {
		if !slices.Contains(diffs, d) {
			diffs = append(diffs, d)
		}
	}
	return diffs, false
}

// knownWrite is one intended difference: a plan id (a trailing "*"
// matches a prefix), a mode ("*" for both), a field ("*" for any, a
// trailing "*" a prefix such as "proj:*") and the reason.
type knownWrite struct{ id, mode, field, reason string }

// The write side's intended differences are baseline/known/write-*.tsv,
// one file per case family so the agents porting each family list theirs
// without editing the same file: write-contract.tsv is generated by record
// from the Go plan contract; the others are written by hand (see
// known/README.md). The read side's are known/read.tsv.
const knownWriteGlob = "write-*.tsv"

// loadKnownWrite reads intended-difference entries from the given files, skipping missing ones.
func loadKnownWrite(paths ...string) ([]knownWrite, error) {
	var out []knownWrite
	for _, path := range paths {
		b, err := os.ReadFile(path)
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, err
		}
		for n, line := range strings.Split(string(b), "\n") {
			if line == "" || strings.HasPrefix(line, "#") {
				continue
			}
			f := strings.Split(line, "\t")
			if len(f) != 4 {
				return nil, fmt.Errorf("%s:%d: want plan id, mode, field and reason", path, n+1)
			}
			out = append(out, knownWrite{f[0], f[1], f[2], f[3]})
		}
	}
	return out, nil
}

// prefixMatch matches a known-file pattern: path.Match globs, whose "*"
// stays within one "/"-separated id component (or within the field).
func prefixMatch(pattern, s string) bool {
	ok, err := path.Match(pattern, s)
	return err == nil && ok || pattern == s
}

// explained reports whether known entries account for every difference.
func explained(known []knownWrite, id, mode string, diffs []string) (string, bool) {
	var reasons []string
	for _, d := range diffs {
		ok := false
		for _, k := range known {
			if prefixMatch(k.id, id) && (k.mode == "*" || k.mode == mode) && fieldMatch(k.field, d) {
				ok = true
				if !slices.Contains(reasons, k.reason) {
					reasons = append(reasons, k.reason)
				}
				break
			}
		}
		if !ok {
			return "", false
		}
	}
	return strings.Join(reasons, "; "), true
}

// selectionFlags are the compare flags that select a subset of the runs.
var selectionFlags = []string{"ops", "kinds", "plan", "modes"}

// narrowingFlags lists the selection flags set on the command line, as
// -name=value, so a partial compare says it is one.
func narrowingFlags(fs *flag.FlagSet) []string {
	var out []string
	fs.Visit(func(f *flag.Flag) {
		if slices.Contains(selectionFlags, f.Name) {
			out = append(out, "-"+f.Name+"="+f.Value.String())
		}
	})
	return out
}

// writeCompareCmd is `oracle write compare`.
func writeCompareCmd(args []string) error {
	fs := flag.NewFlagSet("write compare", flag.ExitOnError)
	var c config
	c.flags(fs)
	oracle := oracleFlag(fs)
	filter := addWriteFilter(fs)
	bin := fs.String("docx", "", "Go docx CLI to compare (default: build ./cmd/docx into -out)")
	show := fs.Int("show", 20, "list at most this many differences")
	strict := fs.Bool("require-implemented", false, "fail on plans the Go CLI does not implement yet")
	fs.Parse(args)
	if err := c.resolve(); err != nil {
		return err
	}
	narrowed := narrowingFlags(fs)
	if *bin == "" {
		*bin = filepath.Join(c.out, "bin", "docx")
		build := exec.Command("go", "build", "-o", *bin, "./cmd/docx")
		build.Dir = c.root
		build.Stdout, build.Stderr = os.Stdout, os.Stderr
		if err := build.Run(); err != nil {
			return fmt.Errorf("build cmd/docx: %w", err)
		}
	}
	oracleBin := c.oracleBin(*oracle)
	jobs, srcs, err := c.writeJobs(filter)
	if err != nil {
		return err
	}
	want, err := c.loadResults()
	if err != nil {
		return err
	}
	paths, err := filepath.Glob(filepath.Join(c.baseline, "known", knownWriteGlob))
	if err != nil {
		return err
	}
	known, err := loadKnownWrite(paths...)
	if err != nil {
		return err
	}
	type row struct {
		op, id, mode, outcome, note string
	}
	var mu sync.Mutex
	var rows []row
	triage := filepath.Join(c.out, "write-compare")
	if err := os.RemoveAll(triage); err != nil {
		return err
	}
	work := filepath.Join(c.out, "write-work-go")
	err = runWriteJobs(jobs, c.jobs, work, func(j writeJob, dir string) error {
		bl := &blobs{m: map[string]string{}}
		got, err := runWrite(goApplier{*bin}, oracleBin, srcs[j.p.Set+"\t"+j.p.File], j.p, j.mode, dir, bl)
		if err != nil {
			return fmt.Errorf("%s %s: %w", j.p.ID, j.mode, err)
		}
		w, ok := want[resultKey(j.p.ID, j.mode)]
		r := row{op: j.p.Op, id: j.p.ID, mode: j.mode}
		switch {
		case !ok:
			r.outcome = wNoBaseline
		case got.unsupported:
			r.outcome = wNotImplemented
		default:
			diffs, oracleBug := compareWrite(w, got), false
			if j.p.Kind == kindDirty {
				diffs, oracleBug = compareDirty(w, got)
			}
			if j.p.Op == opTextInsert {
				diffs = lawDiffs(j.mode, diffs)
			}
			switch reason, ok := explained(known, j.p.ID, j.mode, diffs); {
			case len(diffs) == 0 && oracleBug:
				r.outcome, r.note = wIntended, "docxdriver refuses over a pre-existing defect ("+w.Code+"); Go saves"
			case len(diffs) == 0:
				r.outcome = wIdentical
			case ok:
				r.outcome, r.note = wIntended, reason
			default:
				r.outcome, r.note = wDiffer, strings.Join(diffs, ",")
				if err := c.writeTriage(filepath.Join(triage, strings.ReplaceAll(j.p.ID, "/", "~"), j.mode), oracleBin, srcs[j.p.Set+"\t"+j.p.File], j, dir+"-oracle", got, bl); err != nil {
					return err
				}
			}
		}
		mu.Lock()
		rows = append(rows, r)
		mu.Unlock()
		return nil
	})
	os.RemoveAll(work)
	if err != nil {
		return err
	}
	slices.SortFunc(rows, func(a, b row) int {
		return strings.Compare(a.id+"\t"+a.mode, b.id+"\t"+b.mode)
	})
	var report strings.Builder
	counts := map[string]map[string]int{}
	var shown []string
	bad := 0
	for _, r := range rows {
		if counts[r.op] == nil {
			counts[r.op] = map[string]int{}
		}
		counts[r.op][r.outcome]++
		fmt.Fprintf(&report, "%s\t%s\t%s\t%s\n", r.id, r.mode, r.outcome, r.note)
		if r.outcome == wDiffer || r.outcome == wNoBaseline || (*strict && r.outcome == wNotImplemented) {
			bad++
			if len(shown) < *show {
				shown = append(shown, fmt.Sprintf("  %s %s: %s %s", r.id, r.mode, r.outcome, r.note))
			}
		}
	}
	if err := os.MkdirAll(c.out, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(c.out, "write-compare.tsv"), []byte(report.String()), 0o644); err != nil {
		return err
	}
	fmt.Printf("  %-32s", "op")
	for _, o := range wOutcomes {
		fmt.Printf(" %15s", o)
	}
	fmt.Println()
	for _, op := range opNames() {
		if counts[op] == nil {
			continue
		}
		fmt.Printf("  %-32s", op)
		for _, o := range wOutcomes {
			fmt.Printf(" %15d", counts[op][o])
		}
		fmt.Println()
	}
	for _, s := range shown {
		fmt.Println(s)
	}
	if len(narrowed) > 0 {
		fmt.Printf("oracle: narrowed compare (%s): its counts cover only the selected runs; the gate is the full run (make oracle-write-gate)\n", strings.Join(narrowed, " "))
	}
	if bad > 0 {
		return fmt.Errorf("%d write runs differ from the record (triage under %s)", bad, triage)
	}
	return nil
}

// writeTriage writes both sides' texts of a differing run, JSON
// indented, so a plain diff of the two directories shows the difference.
// The record keeps no texts: the oracle side is run again here (its
// output is deterministic).
func (c *config) writeTriage(dir, oracleBin string, src []byte, j writeJob, work string, got *writeResult, gotTexts *blobs) error {
	oracleTexts := &blobs{m: map[string]string{}}
	want, err := runWrite(oracleApplier{oracleBin}, oracleBin, src, j.p, j.mode, work, oracleTexts)
	if err != nil {
		return err
	}
	texts := oracleTexts.m
	side := func(name string, r *writeResult, t map[string]string) error {
		d := filepath.Join(dir, name)
		if err := os.MkdirAll(d, 0o755); err != nil {
			return err
		}
		files := map[string]string{}
		maps.Copy(files, r.Triage)
		for k, v := range r.Proj {
			_, dg, _ := strings.Cut(v, " ")
			files[k] = dg
		}
		for k, dg := range files {
			if err := os.WriteFile(filepath.Join(d, k+".txt"), indentJSON(t[dg]), 0o644); err != nil {
				return err
			}
		}
		meta, err := json.MarshalIndent(r, "", "  ")
		if err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(d, "result.json"), meta, 0o644)
	}
	if err := side("oracle", want, texts); err != nil {
		return err
	}
	return side("go", got, gotTexts.m)
}

// indentJSON indents a JSON text (a raw step output keeps its header).
func indentJSON(s string) []byte {
	head, body := "", s
	if strings.HasPrefix(s, "exit ") {
		head, body, _ = strings.Cut(s, "\n")
		head += "\n"
	}
	var b strings.Builder
	b.WriteString(head)
	var v any
	if err := json.Unmarshal([]byte(strings.TrimSpace(body)), &v); err != nil {
		b.WriteString(body)
		return []byte(b.String())
	}
	var out bytes.Buffer
	enc := json.NewEncoder(&out)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		b.WriteString(body)
		return []byte(b.String())
	}
	b.Write(out.Bytes())
	return []byte(b.String())
}

// lawDiffs keeps the differences a Go-only law case asserts. A
// text.insert case is recorded as its Equivalent (a text.replace of the
// span by itself plus the new text): in direct mode every projection must
// equal it; in track mode the replacement also records a deletion, so
// only the accept-all projections (the final text) must.
func lawDiffs(mode string, diffs []string) []string {
	if mode != "track" {
		return diffs
	}
	var out []string
	for _, d := range diffs {
		if !strings.HasPrefix(d, "proj:") || strings.HasPrefix(d, "proj:accept-") {
			out = append(out, d)
		}
	}
	return out
}

// fieldMatch matches a known-file field: "*", a prefix ending in "*"
// ("proj:*", "part:*"), or the field itself.
func fieldMatch(pattern, field string) bool {
	if p, ok := strings.CutSuffix(pattern, "*"); ok {
		return strings.HasPrefix(field, p)
	}
	return pattern == field
}
