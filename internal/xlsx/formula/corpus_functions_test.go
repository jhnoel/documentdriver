const functionTableFile = "functions_table.go"

type funcUse struct {
	name, prefix, seen, spill string
}

// TestCorpusFunctionTable regenerates the function table from the
// Excel-authored workbooks of the corpus and requires functions_table.go
// to match. Run with XLSX_FORMULA_UPDATE=1 to rewrite it. It needs the
// whole corpus, so it is skipped on a shard.
func TestCorpusFunctionTable(t *testing.T) {
	_, files := corpusFiles(t)
	if corpustest.Sharded() {
		t.Skip("the table is built from the whole corpus")
	}
	res := corpustest.Run(t, files, func(_ *testing.T, f corpustest.File, r *[]funcUse) {
		cf := readCorpusFile(f.Path)
		if !cf.Excel {
			return
		}
		for _, fm := range cf.Formulas {
			if fm.Kind == "shared-child" || fm.Kind == "data-table" || strings.HasPrefix(fm.Kind, "empty ") {
				continue
			}
			text := fm.Text
			if fm.Kind == "external-name" {
				text = strings.TrimPrefix(text, "=")
			}
			toks := Lex(text)
			if ValidateTokens(toks) != nil {
				continue
			}
			where := f.Name + "!" + fm.Part + "!" + fm.Where
			spill := spillRoot(fm, toks)
			for _, tk := range toks {
				if tk.Kind != Func {
					continue
				}
				pre, rest, _ := SplitQualified(tk.Text)
				if pre.Text != "" {
					continue // external or sheet-qualified: a workbook's own function
				}
				p, base := SplitPrefix(rest)
				if p == PrefixParam || strings.HasPrefix(base, "_xl") {
					continue // _xludf. and _xll.: user-defined and add-in functions
				}
				u := funcUse{name: strings.ToUpper(base), prefix: p, seen: where}
				if spill == tk.Text {
					u.spill = where
				}
				*r = append(*r, u)
			}
		}
	})
	type agg struct {
		count map[string]int
		seen  map[string]string
		spill string
	}
	all := map[string]*agg{}
	for _, r := range res {
		for _, u := range r.Value {
			a := all[u.name]
			if a == nil {
				a = &agg{count: map[string]int{}, seen: map[string]string{}}
				all[u.name] = a
			}
			a.count[u.prefix]++
			if _, ok := a.seen[u.prefix]; !ok {
				a.seen[u.prefix] = u.seen
			}
			if a.spill == "" {
				a.spill = u.spill
			}
		}
	}
	names := make([]string, 0, len(all))
	for n := range all {
		names = append(names, n)
	}
	slices.Sort(names)
	var b strings.Builder
	b.WriteString("// Code generated by TestCorpusFunctionTable from the xlsx corpus; DO NOT EDIT.\n\npackage formula\n\nvar functionTable = [...]Function{\n")
	for _, n := range names {
		a := all[n]
		// The prefix Excel wrote most; ties go to the longer prefix.
		prefixes := make([]string, 0, len(a.count))
		for p := range a.count {
			prefixes = append(prefixes, p)
		}
		slices.SortFunc(prefixes, func(x, y string) int {
			if a.count[x] != a.count[y] {
				return a.count[y] - a.count[x]
			}
			return len(y) - len(x)
		})
		var also []string
		for _, p := range prefixes[1:] {
			k := p
			if k == "" {
				k = "-"
			}
			also = append(also, k+"="+strconv.Itoa(a.count[p]))
		}
		p := prefixes[0]
		fmt.Fprintf(&b, "\t{Name: %q, Prefix: %q, Seen: %q, Count: %d", n, p, a.seen[p], a.count[p])
		if len(also) > 0 {
			fmt.Fprintf(&b, ", Also: %q", strings.Join(also, " "))
		}
		if a.spill != "" {
			fmt.Fprintf(&b, ", Spill: %q", a.spill)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		t.Fatalf("format table: %v", err)
	}
	if os.Getenv("XLSX_FORMULA_UPDATE") != "" {
		if err := os.WriteFile(functionTableFile, src, 0o644); err != nil { //nolint:gosec // G306: a source file
			t.Fatal(err)
		}
		t.Logf("wrote %s: %d functions", functionTableFile, len(names))
		return
	}
	old, err := os.ReadFile(functionTableFile)
	if err != nil {
		t.Fatal(err)
	}
	if string(old) != string(src) {
		t.Errorf("%s is stale; rerun with XLSX_FORMULA_UPDATE=1", functionTableFile)
	}
	t.Logf("function table: %d functions", len(names))
}

// spillRoot returns the root function's token text when fm is a
// multi-cell dynamic-array formula that is one call whose arguments hold
// only constants, operators, separators and single cells; else "".
func spillRoot(fm corpusFormula, toks []Token) string {
	if fm.Kind != "cell" || !fm.CM || fm.T != "array" {
		return ""
	}
	if r, ok := ParseRange(fm.Ref); !ok || r.Single || r.From == r.To {
		return ""
	}
	var core []Token
	for _, tk := range toks {
		if tk.Kind != Space {
			core = append(core, tk)
		}
	}
	if len(core) < 3 || core[0].Kind != Func || core[1].Kind != LParen || core[len(core)-1].Kind != RParen {
		return ""
	}
	for _, tk := range core[2 : len(core)-1] {
		switch tk.Kind {
		case Number, String, Bool, Error, Op, Comma:
		case Ref:
			_, body, _ := SplitQualified(tk.Text)
			if r, _, ok := ParseRefBody(body); !ok || !r.Single {
				return ""
			}
		default:
			return ""
		}
	}
	return core[0].Text
}

// TestCorpusQuoting holds NeedsQuote to what Excel wrote: every sheet
// prefix in an Excel-authored workbook that Excel quoted must be one
// NeedsQuote quotes (else Rename would write it bare). Prefixes NeedsQuote
// quotes but Excel left bare are counted: quoting is always valid.
func TestCorpusQuoting(t *testing.T) {
	_, files := corpusFiles(t)
	type counts struct {
		agree, over   int
		under, overEx []string
	}
	res := corpustest.Run(t, files, func(_ *testing.T, f corpustest.File, r *counts) {
		cf := readCorpusFile(f.Path)
		if !cf.Excel {
			return
		}
		for _, fm := range cf.Formulas {
			if fm.Kind == "external-name" {
				// Excel quotes every sheet in an externalLink refersTo
				// ('Sheet1'!$A$1): a convention of that attribute.
				continue
			}
			for _, tk := range Lex(fm.Text) {
				if tk.Kind != Ref && tk.Kind != Name && tk.Kind != Func {
					continue
				}
				p, _, ok := SplitQualified(tk.Text)
				if !ok || !p.HasSheet() || p.HasBook {
					continue
				}
				need := NeedsQuote(p.First) || p.ThreeD() && NeedsQuote(p.Last)
				switch {
				case need == p.Quoted:
					r.agree++
				case p.Quoted:
					r.under = append(r.under, f.Name+"!"+fm.Part+"!"+fm.Where+": "+tk.Text)
				default:
					r.over++
					r.overEx = append(r.overEx, tk.Text)
				}
			}
		}
	})
	var c counts
	for _, r := range res {
		c.agree += r.Value.agree
		c.over += r.Value.over
		c.under = append(c.under, r.Value.under...)
		c.overEx = append(c.overEx, r.Value.overEx...)
	}
	for _, u := range c.under {
		t.Errorf("Excel quoted a prefix NeedsQuote leaves bare: %s", u)
	}
	slices.Sort(c.overEx)
	c.overEx = slices.Compact(c.overEx)
	t.Logf("sheet prefixes in Excel files: %d agree, %d Excel quoted that NeedsQuote leaves bare, %d NeedsQuote quotes that Excel left bare %q",
		c.agree, len(c.under), c.over, c.overEx[:min(len(c.overEx), 20)])
}
