// The 7x13 fixed font the overlay labels use: every glyph cell is 7 pixels
// wide (6 drawn columns and one blank) and 13 high, with the baseline 11
// rows down.
const (
	fontAdvance = 7
	fontWidth   = 6
	fontHeight  = 13
	fontAscent  = 11
)

// drawText draws s with its first cell's top-left corner at (x, y) in c.
// Characters outside printable ASCII draw as U+FFFD, as basicfont did.
func drawText(img *image.RGBA, x, y int, s string, c color.RGBA) {
	for _, r := range s {
		g := glyph7x13[len(glyph7x13)-1]
		if r >= 0x20 && r < 0x7f {
			g = glyph7x13[r-0x20]
		}
		for row, bits := range g {
			for col := 0; col < fontWidth; col++ {
				if bits&(0x80>>col) != 0 {
					set(img, x+col, y+row, c)
				}
			}
		}
		x += fontAdvance
	}
}

