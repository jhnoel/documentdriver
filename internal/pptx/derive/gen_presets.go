//go:build ignore

// gen_presets extracts the guide, connection-site and (for connectors) path
// definitions of the presets in the site table from ECMA-376's
// presetShapeDefinitions.xml, and writes them as Go source.
//
// The input is not committed. It is the copy in LibreOffice core at the
// commit pinned by eval/corpus/fetch.sh:
//
//	https://raw.githubusercontent.com/LibreOffice/core/83d264f2f0a6f2944d524c9a55cb2a0764d12255/oox/source/drawingml/customshapes/presetShapeDefinitions.xml
//
// Usage (from this directory):
//
//	go run gen_presets.go presetShapeDefinitions.xml > presets_table.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"

	"github.com/jhnoel/documentdriver/internal/ooxml/tree"
)

// sitePresets are the presets whose connection sites are tabulated.
var sitePresets = []string{
	"rect", "roundRect", "ellipse", "diamond", "triangle", "rtTriangle",
	"parallelogram", "trapezoid", "hexagon", "octagon", "can",
	"flowChartProcess", "flowChartAlternateProcess", "flowChartDecision",
	"flowChartTerminator", "flowChartDocument", "flowChartMagneticDisk",
	"flowChartInputOutput", "flowChartPredefinedProcess", "flowChartConnector",
	"flowChartPunchedTape",
}

// pathPresets are the connector presets whose paths are tabulated, for
// endpoints and elbows.
var pathPresets = []string{
	"line", "straightConnector1",
	"bentConnector2", "bentConnector3", "bentConnector4", "bentConnector5",
	"curvedConnector2", "curvedConnector3", "curvedConnector4", "curvedConnector5",
}

// main generates the preset geometry table from the input XML.
func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: go run gen_presets.go presetShapeDefinitions.xml")
		os.Exit(2)
	}
	src, err := os.ReadFile(os.Args[1])
	if err != nil {
		fatal(err)
	}
	doc, err := tree.Parse(src)
	if err != nil {
		fatal(err)
	}
	defs := map[string]*tree.Node{}
	for _, e := range doc.Root().Elements() {
		defs[e.Name()] = e
	}
	want := map[string]bool{}
	for _, p := range sitePresets {
		want[p] = true
	}
	for _, p := range pathPresets {
		want[p] = true
	}
	var names []string
	for n := range want {
		names = append(names, n)
	}
	sort.Strings(names)

	var b bytes.Buffer
	b.WriteString("// Code generated by gen_presets.go from ECMA-376 presetShapeDefinitions.xml; DO NOT EDIT.\n\n")
	b.WriteString("package derive\n\n")
	b.WriteString("var presetTable = map[string]*presetDef{\n")
	for _, n := range names {
		e := defs[n]
		if e == nil {
			fatal(fmt.Errorf("preset %s not in definitions", n))
		}
		fmt.Fprintf(&b, "%q: {\n", n)
		b.WriteString("av: []guide{")
		for _, g := range guides(e, "avLst") {
			fmt.Fprintf(&b, "{%q, %q},", g[0], g[1])
		}
		b.WriteString("},\n")
		b.WriteString("gd: []guide{")
		for _, g := range guides(e, "gdLst") {
			fmt.Fprintf(&b, "{%q, %q},", g[0], g[1])
		}
		b.WriteString("},\n")
		if c := child(e, "cxnLst"); c != nil && isSite(n) {
			b.WriteString("cxn: []cxnDef{")
			for _, cx := range c.Elements() {
				ang, _ := cx.Attr("ang")
				pos := child(cx, "pos")
				x, _ := pos.Attr("x")
				y, _ := pos.Attr("y")
				fmt.Fprintf(&b, "{%q, %q, %q},", ang, x, y)
			}
			b.WriteString("},\n")
		}
		if isPath(n) {
			b.WriteString("paths: []pathDef{")
			for _, p := range child(e, "pathLst").Elements() {
				w, _ := p.Attr("w")
				h, _ := p.Attr("h")
				fmt.Fprintf(&b, "{w: %q, h: %q, cmds: []pathCmd{", w, h)
				for _, c := range p.Elements() {
					fmt.Fprintf(&b, "{op: %q, pts: [][2]string{", c.Name())
					for _, pt := range c.Elements() {
						x, _ := pt.Attr("x")
						y, _ := pt.Attr("y")
						fmt.Fprintf(&b, "{%q, %q},", x, y)
					}
					b.WriteString("}},")
				}
				b.WriteString("}},")
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		fatal(err)
	}
	os.Stdout.Write(out)
}

// isSite reports whether the preset has connection sites.
func isSite(n string) bool {
	for _, p := range sitePresets {
		if p == n {
			return true
		}
	}
	return false
}

// isPath reports whether the preset's path is tabulated.
func isPath(n string) bool {
	for _, p := range pathPresets {
		if p == n {
			return true
		}
	}
	return false
}

// child returns the named child element of e, or nil.
func child(e *tree.Node, local string) *tree.Node {
	for _, c := range e.Elements() {
		if c.Local() == local {
			return c
		}
	}
	return nil
}

// guides returns the name and formula pairs of a guide list.
func guides(e *tree.Node, list string) [][2]string {
	c := child(e, list)
	if c == nil {
		return nil
	}
	var out [][2]string
	for _, g := range c.Elements() {
		name, _ := g.Attr("name")
		fmla, _ := g.Attr("fmla")
		out = append(out, [2]string{name, fmla})
	}
	return out
}

// fatal prints err to stderr and exits 1.
func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gen_presets:", err)
	os.Exit(1)
}
